function initSkillMorePopups() {
  const wraps = document.querySelectorAll(".svc-more-wrap");
  if (!wraps.length) return;

  const closeAll = (except) => {
    wraps.forEach((wrap) => {
      if (wrap === except) return;
      const btn = wrap.querySelector(".svc-tag.more");
      const pop = wrap.querySelector(".svc-more-pop");
      if (btn) btn.setAttribute("aria-expanded", "false");
      if (pop) pop.hidden = true;
    });
  };

  wraps.forEach((wrap) => {
    const btn = wrap.querySelector(".svc-tag.more");
    const pop = wrap.querySelector(".svc-more-pop");
    if (!btn || !pop) return;
    if (btn.dataset.bound === "1") return;
    btn.dataset.bound = "1";

    btn.addEventListener("click", (e) => {
      e.preventDefault();
      e.stopPropagation();
      const open = btn.getAttribute("aria-expanded") === "true";
      closeAll(wrap);
      btn.setAttribute("aria-expanded", open ? "false" : "true");
      pop.hidden = open;
    });
    pop.addEventListener("click", (e) => e.stopPropagation());
  });

  if (!document.body.dataset.skillMoreDoc) {
    document.body.dataset.skillMoreDoc = "1";
    document.addEventListener("click", () => closeAll(null));
    document.addEventListener("keydown", (e) => {
      if (e.key === "Escape") closeAll(null);
    });
  }
}

