// Re-apply modal text on language change
const origApply = applyLanguage;
applyLanguage = function(lang) {
  origApply(lang);
  // Keep scramble text stable after first reveal (no continuous re-run)
  document.querySelectorAll(".hero-tagline .scramble").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (!key) return;
    const keys = key.split(".");
    let val = i18n[lang];
    for (const k of keys) {
      if (val && val[k] !== undefined) val = val[k];
      else { val = undefined; break; }
    }
    if (typeof val === "string") {
      el.dataset.final = val;
      if (el.dataset.scrambled === "1") el.textContent = val;
    }
  });
  // If modal is open, refresh its content
  const modal = document.getElementById('projectModal');
  if (modal && modal.classList.contains('active')) {
    const titleEl = document.getElementById('modalTitle');
    const idx = projectData.findIndex(p => p.en.title === titleEl.textContent || p.id.title === titleEl.textContent);
    if (idx >= 0) {
      const d = projectData[idx][lang] || projectData[idx].en;
      document.getElementById('modalBadge').textContent = d.badge;
      document.getElementById('modalTitle').textContent = d.title;
      document.getElementById('modalBody').innerHTML = d.full;
      const techWrap = document.getElementById('modalTech');
      techWrap.innerHTML = '';
      d.tech.forEach(t => {
        const tag = document.createElement('span');
        tag.className = 'tech-tag';
        tag.textContent = t;
        techWrap.appendChild(tag);
      });
      const impactsWrap = document.getElementById('modalImpacts');
      impactsWrap.innerHTML = '';
      d.impacts.forEach(item => {
        const div = document.createElement('div');
        div.className = 'modal-impact';
        div.textContent = item;
        impactsWrap.appendChild(div);
      });

      // Refresh gallery alt texts
      const galleryItems = document.querySelectorAll('#modalGallery .gallery-item img');
      galleryItems.forEach((img, i) => {
        img.alt = d.title + ' - photo ' + (i + 1);
      });
      const placeholderLabels = document.querySelectorAll('#modalGallery .gallery-placeholder');
      if (placeholderLabels.length) {
        const label = d.title.split(' ').slice(0, 2).map(w => w[0]).join('');
        placeholderLabels.forEach(el => { el.textContent = label; });
      }
    }
  }
};

