function initCustomCursor() {
  const isTouch = 'ontouchstart' in window || navigator.maxTouchPoints > 0;
  if (isTouch) return;

  const dot = document.getElementById('cursorDot');
  const ring = document.getElementById('cursorRing');
  if (!dot || !ring) return;

  let mouseX = 0, mouseY = 0;
  let ringX = 0, ringY = 0;
  let rafId;

  document.addEventListener('mousemove', e => {
    mouseX = e.clientX;
    mouseY = e.clientY;
    dot.style.left = mouseX + 'px';
    dot.style.top = mouseY + 'px';
  });

  function animateRing() {
    ringX += (mouseX - ringX) * 0.12;
    ringY += (mouseY - ringY) * 0.12;
    ring.style.left = ringX + 'px';
    ring.style.top = ringY + 'px';
    rafId = requestAnimationFrame(animateRing);
  }
  animateRing();

  const hoverTargets = document.querySelectorAll(
    'a, button, .btn-primary, .btn-secondary, .btn-ghost, .skill-card, .project-card, .tl-card, .toggle-switch, .wa-float, .nav-cta'
  );
  hoverTargets.forEach(el => {
    el.addEventListener('mouseenter', () => {
      dot.classList.add('active');
      ring.classList.add('active');
    });
    el.addEventListener('mouseleave', () => {
      dot.classList.remove('active');
      ring.classList.remove('active');
    });
  });

  document.addEventListener('mouseleave', () => {
    dot.style.opacity = '0';
    ring.style.opacity = '0';
  });
  document.addEventListener('mouseenter', () => {
    dot.style.opacity = '1';
    ring.style.opacity = '1';
  });
}

// ============================================
// PARTICLES + SNAKE TRAIL (hero banner)
// ============================================
function initParticles() {
  // Tear down previous loop (React Strict Mode / re-boot)
  if (typeof window.__particlesCleanup === "function") {
    window.__particlesCleanup();
    window.__particlesCleanup = null;
  }

  const prefersReduced = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  if (prefersReduced) return;

  const canvas = document.getElementById('particlesCanvas');
  if (!canvas) return;

  const ctx = canvas.getContext('2d');
  let particles = [];
  let animId = 0;
  let t = 0;
  let started = false;

  // Snake bodies (auto-crawling)
  const snakes = [];
  const SEGMENTS = 28;
  const SNAKE_COUNT = 2;

  function isDarkTheme() {
    return document.documentElement.getAttribute('data-theme') !== 'light';
  }

  function resize() {
    const host = canvas.parentElement || document.getElementById('hero');
    if (!host) return false;
    const rect = host.getBoundingClientRect();
    if (rect.width < 2 || rect.height < 2) return false;
    const dpr = Math.min(window.devicePixelRatio || 1, 2);
    canvas.width = Math.floor(rect.width * dpr);
    canvas.height = Math.floor(rect.height * dpr);
    canvas.style.width = rect.width + 'px';
    canvas.style.height = rect.height + 'px';
    ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
    canvas._cssW = rect.width;
    canvas._cssH = rect.height;
    return true;
  }

  function createSnake(seed) {
    const segs = [];
    for (let i = 0; i < SEGMENTS; i++) segs.push({ x: 0, y: 0 });
    return {
      segs,
      seed,
      speed: 0.010 + seed * 0.004,
      ampX: 0.28 + seed * 0.08,
      ampY: 0.18 + seed * 0.05,
      thickness: 5.5 - seed * 1.2
    };
  }

  function createParticles() {
    const w = canvas._cssW || 800;
    const h = canvas._cssH || 360;
    particles = [];
    for (let i = 0; i < 22; i++) {
      particles.push({
        x: Math.random() * w,
        y: Math.random() * h,
        size: Math.random() * 1.2 + 0.3,
        speedX: (Math.random() - 0.5) * 0.2,
        speedY: (Math.random() - 0.5) * 0.2,
        opacity: Math.random() * 0.18 + 0.04
      });
    }
  }

  function setupSnakes() {
    snakes.length = 0;
    for (let i = 0; i < SNAKE_COUNT; i++) snakes.push(createSnake(i));
  }

  function snakeHead(snake, w, h, time) {
    const s = snake.seed;
    // Smooth wandering path inside banner
    const x =
      w * 0.5 +
      Math.sin(time * snake.speed + s * 2.1) * w * snake.ampX +
      Math.sin(time * snake.speed * 1.7 + s) * w * 0.08;
    const y =
      h * 0.55 +
      Math.cos(time * snake.speed * 0.9 + s * 1.4) * h * snake.ampY +
      Math.sin(time * snake.speed * 1.3 + s * 0.6) * h * 0.08;
    return {
      x: Math.max(24, Math.min(w - 24, x)),
      y: Math.max(28, Math.min(h - 28, y))
    };
  }

  function updateSnake(snake, w, h) {
    const head = snakeHead(snake, w, h, t);
    const segs = snake.segs;
    // Head moves to target; body follows with easing lag
    segs[0].x += (head.x - segs[0].x) * 0.28;
    segs[0].y += (head.y - segs[0].y) * 0.28;
    for (let i = 1; i < segs.length; i++) {
      const prev = segs[i - 1];
      const cur = segs[i];
      const dx = prev.x - cur.x;
      const dy = prev.y - cur.y;
      const dist = Math.sqrt(dx * dx + dy * dy) || 1;
      const spacing = 7.5;
      const targetX = prev.x - (dx / dist) * spacing;
      const targetY = prev.y - (dy / dist) * spacing;
      cur.x += (targetX - cur.x) * 0.45;
      cur.y += (targetY - cur.y) * 0.45;
    }
  }

  function drawSnake(snake, rgb) {
    const segs = snake.segs;
    // Soft ribbon trail
    for (let i = segs.length - 1; i >= 1; i--) {
      const a = segs[i];
      const b = segs[i - 1];
      const progress = 1 - i / segs.length;
      const alpha = 0.08 + progress * 0.45;
      const width = snake.thickness * (0.35 + progress * 0.9);
      ctx.beginPath();
      ctx.strokeStyle = `rgba(${rgb}, ${alpha})`;
      ctx.lineWidth = width;
      ctx.lineCap = "round";
      ctx.lineJoin = "round";
      ctx.moveTo(a.x, a.y);
      ctx.lineTo(b.x, b.y);
      ctx.stroke();
    }
    // Head glow
    const h = segs[0];
    const g = ctx.createRadialGradient(h.x, h.y, 0, h.x, h.y, 14);
    g.addColorStop(0, `rgba(${rgb}, 0.55)`);
    g.addColorStop(1, `rgba(${rgb}, 0)`);
    ctx.beginPath();
    ctx.fillStyle = g;
    ctx.arc(h.x, h.y, 14, 0, Math.PI * 2);
    ctx.fill();
    ctx.beginPath();
    ctx.fillStyle = `rgba(${rgb}, 0.85)`;
    ctx.arc(h.x, h.y, 3.2, 0, Math.PI * 2);
    ctx.fill();
  }

  function drawFrame() {
    const w = canvas._cssW || canvas.width;
    const h = canvas._cssH || canvas.height;
    ctx.clearRect(0, 0, w, h);
    t += 1;

    const dark = isDarkTheme();
    const baseColor = dark ? '255, 255, 255' : '20, 20, 20';
    const snakeColor = dark ? '235, 235, 240' : '30, 30, 35';

    // Ambient dots
    for (const p of particles) {
      p.x += p.speedX;
      p.y += p.speedY;
      if (p.x < 0) p.x = w;
      if (p.x > w) p.x = 0;
      if (p.y < 0) p.y = h;
      if (p.y > h) p.y = 0;
      ctx.beginPath();
      ctx.arc(p.x, p.y, p.size, 0, Math.PI * 2);
      ctx.fillStyle = `rgba(${baseColor}, ${p.opacity})`;
      ctx.fill();
    }

    for (const snake of snakes) {
      updateSnake(snake, w, h);
      drawSnake(snake, snakeColor);
    }

    animId = requestAnimationFrame(drawFrame);
  }

  function seedSnakes() {
    const w = canvas._cssW || 800;
    const h = canvas._cssH || 360;
    snakes.forEach((snake, si) => {
      for (let i = 0; i < SEGMENTS; i++) {
        const head = snakeHead(snake, w, h, i * 2 + si * 40);
        snake.segs[i].x = head.x;
        snake.segs[i].y = head.y;
      }
      for (let k = 0; k < 20; k++) updateSnake(snake, w, h);
    });
  }

  function start() {
    if (!resize()) return false;
    createParticles();
    setupSnakes();
    seedSnakes();
    if (!started) {
      started = true;
      drawFrame();
    }
    return true;
  }

  const onResize = () => {
    if (resize()) createParticles();
  };
  window.addEventListener("resize", onResize);

  const host = canvas.parentElement;
  let ro;
  if (host && typeof ResizeObserver !== "undefined") {
    ro = new ResizeObserver(() => {
      if (!started) start();
      else onResize();
    });
    ro.observe(host);
  }

  // If layout isn't ready yet (common with React + Lenis), retry a few frames
  if (!start()) {
    let tries = 0;
    const retry = () => {
      tries += 1;
      if (start() || tries > 120) return;
      animId = requestAnimationFrame(retry);
    };
    animId = requestAnimationFrame(retry);
  }

  window.__particlesCleanup = () => {
    cancelAnimationFrame(animId);
    window.removeEventListener("resize", onResize);
    if (ro) ro.disconnect();
    started = false;
  };
}

window.initParticles = initParticles;

