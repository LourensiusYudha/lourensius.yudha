// SCRAMBLE EFFECT — HERO TAGLINE
// ============================================
function scrambleText(el, finalText, options) {
  const opts = options || {};
  const chars = "!<>-_\\/[]{}—=+*^?#________ABCDEFGHIJKLMNOPQRSTUVWXYZ01";
  const duration = opts.duration || 900;
  const delay = opts.delay || 0;
  const frameRate = 45;
  const totalFrames = Math.round(duration / frameRate);

  let frame = 0;
  let timer = null;

  function tick() {
    let output = "";
    const progress = frame / totalFrames;
    for (let i = 0; i < finalText.length; i++) {
      const ch = finalText[i];
      if (ch === " ") { output += " "; continue; }
      const revealAt = (i / finalText.length) * 0.6;
      if (progress >= revealAt + 0.4 || frame >= totalFrames) {
        output += ch;
      } else if (progress >= revealAt) {
        output += chars[Math.floor(Math.random() * chars.length)];
      } else {
        output += chars[Math.floor(Math.random() * chars.length)];
      }
    }
    el.textContent = output;
    frame++;
    if (frame > totalFrames) {
      el.textContent = finalText;
      clearInterval(timer);
      if (typeof opts.onDone === "function") opts.onDone();
    }
  }

  setTimeout(() => {
    timer = setInterval(tick, frameRate);
  }, delay);
}

function initScramble() {
  const prefersReduced = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  const els = document.querySelectorAll(".hero-tagline .scramble");
  els.forEach((el, i) => {
    if (el.dataset.scrambled === "1") {
      if (el.dataset.final) el.textContent = el.dataset.final;
      return;
    }
    const finalText = (el.dataset.final || el.textContent).trim();
    el.dataset.final = finalText;
    if (prefersReduced) {
      el.textContent = finalText;
      el.dataset.scrambled = "1";
      return;
    }
    scrambleText(el, finalText, {
      duration: 1100,
      delay: 400 + i * 320,
      onDone: () => { el.dataset.scrambled = "1"; }
    });
  });
}

