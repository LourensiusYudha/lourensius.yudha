let lightboxData = { projectIdx: -1, imgIdx: 0, images: [] };

function openLightbox(projectIdx, imgIdx) {
  const data = projectData[projectIdx];
  if (!data || !data.images || !data.images.length) return;

  lightboxData = {
    projectIdx,
    imgIdx,
    images: data.images
  };

  updateLightboxImage();
  document.getElementById('lightbox').classList.add('active');
  document.body.style.overflow = 'hidden';
}

function closeLightbox(e) {
  if (e && e.target !== document.getElementById('lightbox')) return;
  document.getElementById('lightbox').classList.remove('active');
  document.body.style.overflow = '';
}

function navigateLightbox(dir) {
  const total = lightboxData.images.length;
  if (total <= 1) return;
  lightboxData.imgIdx = (lightboxData.imgIdx + dir + total) % total;
  updateLightboxImage();
}

function updateLightboxImage() {
  const img = document.getElementById('lightboxImg');
  const counter = document.getElementById('lightboxCounter');
  const prev = document.getElementById('lbPrev');
  const next = document.getElementById('lbNext');

  const fileName = lightboxData.images[lightboxData.imgIdx];
  img.src = 'images/projects/' + fileName;

  counter.textContent = (lightboxData.imgIdx + 1) + ' / ' + lightboxData.images.length;

  const show = lightboxData.images.length > 1;
  prev.style.display = show ? 'flex' : 'none';
  next.style.display = show ? 'flex' : 'none';

  // Fallback if image fails
  img.onerror = function() {
    this.alt = 'Image not available';
    this.style.objectFit = 'contain';
    this.style.padding = '40px';
    this.style.background = 'rgba(255,255,255,0.05)';
    this.style.borderRadius = '8px';
  };
}

document.addEventListener('keydown', e => {
  if (e.key === 'Escape') {
    const lb = document.getElementById('lightbox');
    if (lb.classList.contains('active')) {
      lb.classList.remove('active');
      document.body.style.overflow = '';
      return;
    }
    const modal = document.getElementById('projectModal');
    if (modal.classList.contains('active')) {
      modal.classList.remove('active');
      document.body.style.overflow = '';
    }
  }
});

