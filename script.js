function openDetail(index) {
  const lang = currentLang;
  const data = projectData[index];
  if (!data) return;

  const d = data[lang] || data.en;

  document.getElementById('modalBadge').textContent = d.badge;
  document.getElementById('modalTitle').textContent = d.title;
  document.getElementById('modalBody').innerHTML = d.full;

  const techWrap = document.getElementById('modalTech');
  techWrap.innerHTML = '';
  d.tech.forEach(t => {
    const tag = document.createElement('span');
    tag.className = 'tech-tag';
    tag.textContent = t;
    techWrap.appendChild(tag);
  });

  const impactsWrap = document.getElementById('modalImpacts');
  impactsWrap.innerHTML = '';
  d.impacts.forEach(item => {
    const div = document.createElement('div');
    div.className = 'modal-impact';
    div.textContent = item;
    impactsWrap.appendChild(div);
  });

  // Render gallery
  const galleryWrap = document.getElementById('modalGallery');
  galleryWrap.innerHTML = '';
  if (data.images && data.images.length > 0) {
    const scroll = document.createElement('div');
    scroll.className = 'gallery-scroll';
    const gradients = [
      'linear-gradient(135deg, #0c1a2e, #0f2d50)',
      'linear-gradient(135deg, #0c1e1a, #0f3020)',
      'linear-gradient(135deg, #1a0c2e, #2d0f50)',
      'linear-gradient(135deg, #1a1a0c, #2e3000)'
    ];
    const gradient = gradients[index % gradients.length];

    data.images.forEach((fileName, i) => {
      const item = document.createElement('div');
      item.className = 'gallery-item';

      const img = document.createElement('img');
      img.src = 'images/projects/' + fileName;
      img.alt = d.title + ' - photo ' + (i + 1);
      img.loading = 'lazy';

      img.onerror = function() {
        this.style.display = 'none';
        const placeholder = document.createElement('div');
        placeholder.className = 'gallery-placeholder';
        placeholder.style.background = gradient;
        const label = d.title.split(' ').slice(0, 2).map(w => w[0]).join('');
        placeholder.textContent = label;
        item.appendChild(placeholder);
      };

      img.onclick = function(e) {
        e.stopPropagation();
        openLightbox(index, i);
      };

      const count = document.createElement('div');
      count.className = 'gallery-count';
      count.textContent = (i + 1) + '/' + data.images.length;

      item.appendChild(img);
      item.appendChild(count);
      scroll.appendChild(item);
    });

    galleryWrap.appendChild(scroll);
  }

  document.getElementById('projectModal').classList.add('active');
  document.body.style.overflow = 'hidden';
}

function closeDetail(e) {
  if (e && e.target !== document.getElementById('projectModal')) return;
  document.getElementById('projectModal').classList.remove('active');
  document.body.style.overflow = '';
}

