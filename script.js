// TYPING EFFECT — HERO
// ============================================
function initTypingEffect() {
  const el = document.querySelector(".headline-em");
  if (!el) return;
  const finalText = el.textContent;
  el.textContent = "";
  el.style.display = "inline";
  el.style.borderRight = "2px solid var(--accent)";
  el.style.animation = "none";

  let i = 0;
  function type() {
    if (i < finalText.length) {
      el.textContent += finalText.charAt(i);
      i++;
      setTimeout(type, 40 + Math.random() * 30);
    } else {
      el.style.borderRight = "2px solid transparent";
      setInterval(() => {
        el.style.borderRightColor =
          el.style.borderRightColor === "transparent" ? "var(--accent)" : "transparent";
      }, 530);
    }
  }
  setTimeout(type, 1800);
}

